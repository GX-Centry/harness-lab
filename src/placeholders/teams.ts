/**
 * 【接口保留】Agent Teams —— 从「树形 fan-out」到「网状协作」的接入位。
 *
 * 状态：ADR-010「暂缓」——只保留接口与接入点分析，不实现调度与消息总线。
 *
 * ┌─────────────────────────────────────────────────────────────────────┐
 * │ 先分清：Teams ≠ Sub-agent（已有能力），差在哪？                        │
 * └─────────────────────────────────────────────────────────────────────┘
 *
 *   w13 的 sub-agent 形态（orchestrator fan-out）：
 *     父 ──spawn──> 子A（一次性任务，只回摘要）
 *       └──spawn──> 子B（同理）
 *     拓扑是**树**，边是**一次性**的：任务分派下去、摘要收回来，结束。
 *
 *   Agent Teams 形态（本文件的保留对象）：
 *     成员A ←──消息──> 成员B ←──消息──> 成员C
 *     拓扑是**网**，边是**持续**的：worker 之间互相要信息、多轮协商、
 *     可能带「角色分工 + 共享黑板（blackboard）」。
 *
 *   关键差异不是「数量」，而是**控制流**：fan-out 的结果聚合是
 *   supervisor 一次的收尾动作；Teams 的协作是「谁也不知道要几个回合」
 *   的持续过程。
 *
 * ┌─────────────────────────────────────────────────────────────────────┐
 * │ 为什么暂缓（与当前形态的真实冲突）                                     │
 * └─────────────────────────────────────────────────────────────────────┘
 *
 * ① 内核叙事冲突（最根本）：我们的 Loop 是「一个循环 + 一条消息链」——
 *    可讲解性的基石。Teams 要求把 Loop 升级为**调度器**：多代理并行、
 *    消息路由、死锁/活锁可能性、协商终止条件——每一项都是一篇论文，
 *    与 P0「全链路可讲解」的目标直接冲突（这也是 ADR-010 的立项理由）。
 *
 * ② 消息语义 vs 事件语义（一个容易被忽视的区分）：EventBus 是**广播 +
 *    不可变审计流**（订阅者只读，重复消费无害）；Teams 的消息是
 *    **有归属、可消费、改变系统状态**的（收件箱语义：消息被 A 取走，
 *    B 就不能再取）。把「消息队列」硬塞进「事件总线」会破坏前者的
 *    「宁可不消费不可变」审计契约（w14 的 Tracer 依赖此契约）。
 *    结论：解冻时需要独立的 TeamChannel，而不是复用 EventBus。
 *
 * ③ 成本与可观测爆炸：N 个成员互相发消息 = 无法用「一次 query 一棵树」
 *    模型归因（w13 的 queryId 派生 `父q>agent` 是树形命名法）——
 *    网状通信需要新的归因模型（这是 w14 账本要回答的新问题）。
 *
 * ┌─────────────────────────────────────────────────────────────────────┐
 * │ 未来接入点（解冻时按此接线）                                           │
 * └─────────────────────────────────────────────────────────────────────┘
 *
 * 1. 成员定义**直接复用** SubAgentDefinition（名字/系统提示/工具子集
 *    /超时——一个成员就是「注册到团队目录里的子代理」）——不发明第二套
 *    定义形状。
 * 2. 成员间通信走 TeamChannel（② 的独立实现），成员收消息的循环可以
 *    仍是 w13 的「子 Loop 跑一次任务」——即 Teams 的第一阶段落地可以是
 *    「带共享黑板的 fan-out」（成员读写黑板，supervisor 多轮派发），
 *    而不必一步跳到全异步消息代理。
 * 3. 子代理已有的装配红利照常继承：childRegistry 工具子集、权限门、
 *    hook 链、独立 Provider——成员不是新物种，是「用消息连起来的
 *    子代理们」。
 *
 * 解冻条件（两者同时成立）：
 *   1. fan-out 模式遇到「worker 间必须交换中间信息 / 多轮协商」的真实
 *      任务（单轮分派无法表达）；
 *   2. 多代理网状通信的成本归因模型定稿（冲突 ③）。
 *
 * 依赖说明：只做 type 导入（复用 subagent 的定义形状）——零运行时依赖。
 */

import type { SubAgentDefinition } from '../subagent/types.ts';

// ===========================================================================
// §1 成员与消息
// ===========================================================================

/**
 * 团队成员：子代理定义 + 团队角色。
 * 刻意不新建「成员定义」形状——role 只是给 supervisor 排班看的标签，
 * 执行语义完全由复用的 SubAgentDefinition 承载。
 */
export interface TeamMember {
  /** 成员 id（团队内唯一；用作消息路由地址与黑板署名） */
  readonly id: string;
  /** 角色描述（如 'researcher' / 'critic' / 'writer'——supervisor 按此分工） */
  readonly role: string;
  /** 复用的子代理定义（系统提示 / 工具子集 / 超时——w13 的全部机制） */
  readonly definition: SubAgentDefinition;
}

/** 消息路由地址：某个成员，或广播（'*'——如「黑板有新条目」通知） */
export type TeamRecipient = string;

/** 成员间的一条消息 */
export interface TeamMessage {
  readonly id: string;
  readonly from: string;
  /** 收件人成员 id 或 '*'（广播） */
  readonly to: TeamRecipient;
  readonly content: string;
  readonly ts: number;
}

/**
 * 团队通道（② 的独立消息语义）：post 投递、inbox 消费。
 * 与 EventBus 的契约差异是有意的——这里的 inbox 有**取走**语义
 * （消费后不可再读），不做重复投递保证。
 */
export interface TeamChannel {
  post(message: TeamMessage): void;
  /** 订阅某成员收件箱（含发给它的定向消息与广播） */
  inbox(memberId: string): AsyncIterable<TeamMessage>;
}

// ===========================================================================
// §2 调度形状（最小化：只定一阶段落地的「带黑板 fan-out」）
// ===========================================================================

/**
 * 共享黑板：成员读写任务中间产物（比消息更「持久」的协作载体）。
 * 一阶段落地的中枢——supervisor 每轮读黑板决定下一批派发。
 */
export interface SharedBlackboard {
  /** 写条目（署名成员 id；同名覆盖语义由实现定稿） */
  write(key: string, value: string, author: string): void;
  read(key: string): string | undefined;
  /** 全部条目快照（本轮派发决策的输入） */
  entries(): ReadonlyMap<string, { value: string; author: string }>;
}

/**
 * 团队调度器：把「一次性 fan-out」升级为「多轮派发直到黑板满足验收」。
 * 返回 PENDING 的典型原因：终止条件（何时宣布完成）需要真实用例来定稿，
 * 当前只保留形状。
 */
export interface TeamSupervisor {
  /** 派发一轮：按黑板现状给成员分配任务（返回分配记录供审计） */
  planRound(): Promise<readonly { memberId: string; task: string }[]>;
  /** 验收：黑板是否已满足完成条件（false = 继续下一轮） */
  isSatisfied(): boolean;
}
