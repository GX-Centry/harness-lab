/**
 * 【接口保留】STT（语音转写）—— 「语音输入」到「文本 query」的接入位。
 *
 * 状态：ADR-010「暂缓」——只保留接口与接入点分析，不实现音频处理。
 *
 * ┌─────────────────────────────────────────────────────────────────────┐
 * │ 为什么暂缓（与当前形态的真实冲突）                                     │
 * └─────────────────────────────────────────────────────────────────────┘
 *
 * ① 管线的起点不同：我们的输入层是「readline 返回一行字符串」——一行即
 *    一次 query 的完整输入；语音是**字节流**（采样率/编码/容器格式），
 *    需要采集、上传、转写三段管线，全部在「内核兴趣范围」之外。
 *
 * ② 交互节奏冲突：REPL 是「用户完整输入 → 回车 → 发起 query」；而语音的
 *    自然形态是**边说边出字**（部分转写）——若把「流式部分转写」也当输入，
 *    就出现了「什么时候算说完」的端点检测（VAD）问题。这属于输入层状态机，
 *    与「query 一经发起就有明确生命周期」的内核模型不一致。
 *
 * ③ 隐私与存储：音频数据是否落盘（session 审计口径是「消息文本」）——
 *    引入音频后，审计/记忆/上下文三层都要回答「音频算不算消息」。
 *
 * ┌─────────────────────────────────────────────────────────────────────┐
 * │ 未来接入点（解冻时按此接线，内核零改动）                                │
 * └─────────────────────────────────────────────────────────────────────┘
 *
 * 解冻后 STT 的定位非常清晰：**它只是输入层的又一种实现**——
 *
 *   音频采集 → SpeechToTextProvider.transcribe() → 文本
 *     → 走与键盘输入**完全相同**的管道（commandRouter 拦截 → runQuery）
 *
 * 也就是说 CLI 的 REPL 循环体（「一行输入」→「一次 runQuery」）不需要
 * 任何修改：把 transcribe 的输出当作「那一行」即可（输入源可插拔是
 * readline 抽象的天然能力）。这是「界面与内核分离」的又一次兑现。
 *
 * 解冻条件：出现「语音输入」的真实需求，且选定转写供应商（云 API 或
 * 本地模型——决定 ② 的端点检测由谁负责）并定稿音频的隐私策略（冲突 ③）。
 *
 * 依赖说明：零运行时依赖（只有类型）。
 */

// ===========================================================================
// §1 输入形状
// ===========================================================================

/** 音频容器格式（枚举覆盖主流；具体支持的子集由实现方声明） */
export type AudioFormat = 'wav' | 'mp3' | 'webm-opus' | 'pcm16';

/** 一段待转写音频：字节 + 格式元数据（采样率等由格式隐含或实现方约定） */
export interface AudioInput {
  readonly format: AudioFormat;
  readonly data: Uint8Array;
}

// ===========================================================================
// §2 转写协议
// ===========================================================================

/** 转写结果：文本 + 可选置信度/分段（分段对接「字幕时间轴」类展示需求） */
export interface TranscriptionResult {
  readonly text: string;
  /** 整体置信度（0-1）；供应商不提供时为 undefined——「宁缺毋滥」同 w14 原则 */
  readonly confidence?: number;
  /** 分段转写（每段含起止时间，单位毫秒） */
  readonly segments?: readonly {
    readonly text: string;
    readonly startMs: number;
    readonly endMs: number;
  }[];
}

/**
 * 转写提供方抽象（与 LLMProvider 同构的设计：接口在内核侧定义，
 * 实现按供应商替换）。signal 支持取消——用户在转写中途按 Esc 的场景。
 */
export interface SpeechToTextProvider {
  readonly name: string;
  transcribe(
    audio: AudioInput,
    options?: { readonly language?: string; readonly signal?: AbortSignal },
  ): Promise<TranscriptionResult>;
}

// ===========================================================================
// §3 可选：流式部分转写（端点检测的承载者——见文件头冲突 ②）
// ===========================================================================

/**
 * 流式转写（解冻时才需要实现）：逐步产出部分结果，由**调用方**（输入层
 * 状态机）决定「何时算说完、何时把 final 文本交给 query 管道」。
 * 注意职责划界：本接口只产事件，不理解「回车」；端点检测是输入层的
 * 职责——保持内核「query 一经发起即完整输入」的模型不被侵蚀。
 */
export interface StreamingTranscriber {
  /** 推入一段音频（采集回调） */
  push(chunk: Uint8Array): void;
  /** 结束输入（用户松手/静音超时）→ 产出 final */
  finish(): Promise<TranscriptionResult>;
  /** 订阅部分转写（展示用，不驱动 query） */
  onPartial(handler: (text: string) => void): void;
}
